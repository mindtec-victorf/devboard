#!/usr/bin/env python3
"""Build skills/devboard/web/agent-icons.js: the icon shown next to an agent's name on the page.

Icons come from Simple Icons (CC0, https://simpleicons.org) at a pinned version, so the output is
reproducible. OpenAI asked Simple Icons to remove its logo, so Codex/OpenAI agents get a neutral icon.
Trademarks belong to their owners; the icons only identify which tool an agent is.
    python3 docs/make-agent-icons.py
"""
import json
import re
import urllib.request
from pathlib import Path

VERSION = "16.35.0"
CDN = f"https://cdn.jsdelivr.net/npm/simple-icons@{VERSION}"
OUT = Path(__file__).resolve().parents[1] / "skills" / "devboard" / "web" / "agent-icons.js"
# kind -> (simple-icons slug or None, title); the agent name's first word picks the kind
KINDS = {"claude": ("claude", "Claude"), "gemini": ("googlegemini", "Gemini"), "copilot": ("githubcopilot", "GitHub Copilot"),
         "cursor": ("cursor", "Cursor"), "openai": (None, "OpenAI Codex")}
PREFIXES = {"claude": "claude", "anthropic": "claude", "gemini": "gemini", "google": "gemini", "copilot": "copilot",
            "github": "copilot", "cursor": "cursor", "codex": "openai", "openai": "openai", "gpt": "openai", "chatgpt": "openai"}


def get(url):
    with urllib.request.urlopen(url, timeout=30) as r:
        return r.read().decode("utf-8")


def main():
    data = {i["slug"]: i for i in json.loads(get(f"{CDN}/data/simple-icons.json")) if "slug" in i}
    icons = {}
    for kind, (slug, title) in KINDS.items():
        if slug is None:
            icons[kind] = {"title": title, "hex": None, "path": None}
            continue
        svg = get(f"{CDN}/icons/{slug}.svg")
        icons[kind] = {"title": title, "hex": data[slug]["hex"], "path": re.search(r'<path d="([^"]+)"', svg).group(1)}
    OUT.write_text(
        f"// Generated by docs/make-agent-icons.py from Simple Icons {VERSION} (CC0). Trademarks belong to their owners.\n"
        f"const AGENT_ICONS = {json.dumps(icons, indent=1)};\n"
        f"const AGENT_PREFIXES = {json.dumps(PREFIXES)};\n", encoding="utf-8")
    print("written", OUT.name, sorted(icons))


if __name__ == "__main__":
    main()
